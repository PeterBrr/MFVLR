"""Approved L01 engineering interpretation of MFVLR Fig. 6 / III-D p. 6."""
from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from types import MappingProxyType


GENERATOR_REGISTRY = MappingProxyType({
    "DDPM": ("EFS", "diffusion"),
    "LatentDiffusion": ("EFS", "diffusion"),
    "CollaborativeDiffusion": ("EFS", "diffusion"),
    "StyleGAN3": ("EFS", "GAN"),
    "DiffFace": ("FS", "diffusion"),
    "FSLSD": ("FS", "GAN"),
    "FaceSwapper": ("FS", "GAN"),
    "Diffae": ("AM", "diffusion"),
    "LatentTransformer": ("AM", "GAN"),
})
TYPE_PROMPTS = MappingProxyType({
    "EFS": "A photo of an entire synthesized face",
    "FS": "A photo of an identity swapped face",
    "AM": "A photo of an attribute manipulated face",
})


@dataclass(frozen=True)
class PromptMetadata:
    sample_id: str
    authenticity: str
    manipulation: str | None = None
    family: str | None = None
    generator: str | None = None


class PromptBuilder:
    """Strict, finite registry; no inferred labels, aliases, or dataset loading."""

    @classmethod
    def from_config(cls, config):
        config.require_approval()
        return cls()

    def build(self, records: Sequence[PromptMetadata]) -> tuple[tuple[str, ...], ...]:
        if not isinstance(records, Sequence) or isinstance(records, (str, bytes)):
            raise TypeError("records must be a sequence of PromptMetadata")
        if not records:
            raise ValueError("records must have a positive batch size")
        return tuple(self._one(record) for record in records)

    @staticmethod
    def _one(record: PromptMetadata) -> tuple[str, ...]:
        if not isinstance(record, PromptMetadata):
            raise TypeError("every record must be PromptMetadata")
        if type(record.sample_id) is not str or not record.sample_id:
            raise ValueError("sample_id must be a nonempty string")
        if type(record.authenticity) is not str or record.authenticity not in ("real", "fake"):
            raise ValueError(f"{record.sample_id}: authenticity must be real or fake")
        if record.authenticity == "real":
            return ("A photo of a real face",) * 4
        fields = (record.manipulation, record.family, record.generator)
        if any(type(value) is not str or not value for value in fields):
            raise ValueError(f"{record.sample_id}: fake metadata needs manipulation, family and generator")
        if record.generator not in GENERATOR_REGISTRY:
            raise ValueError(f"{record.sample_id}: unknown generator {record.generator!r}; no alias inference")
        if (record.manipulation, record.family) != GENERATOR_REGISTRY[record.generator]:
            raise ValueError(f"{record.sample_id}: generator/type/family combination is inconsistent")
        return (
            "A photo of a fake face", TYPE_PROMPTS[record.manipulation],
            f"A photo generated by the {record.family}-based model",
            f"The source generative model of this photo is {record.generator}",
        )
