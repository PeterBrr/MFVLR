"""Independent golden oracle: pinned upstream tokenizer + upstream tokenize AST.

This utility deliberately imports no mfvlr production module. It never imports
CLIP's model-loading module: only its tokenize function is AST-extracted.
"""
from pathlib import Path
import ast
import hashlib
import importlib.metadata
import importlib.util
import json
from typing import List, Union

from packaging import version
import torch

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "src/mfvlr/tokenizer_assets"


def digest_json(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, separators=(",", ":")).encode()).hexdigest()


def official_oracle():
    manifest = json.loads((ASSETS / "manifest.json").read_text(encoding="utf-8"))
    for name, record in manifest["files"].items():
        assert hashlib.sha256((ASSETS / name).read_bytes()).hexdigest() == record["sha256"]
    for name, expected in manifest["dependencies"].items():
        assert importlib.metadata.version(name) == expected, name
    spec = importlib.util.spec_from_file_location("pinned_official_clip_tokenizer", ASSETS / "clip/simple_tokenizer.py")
    source = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(source)
    tokenizer = source.SimpleTokenizer(str(ASSETS / "clip/bpe_simple_vocab_16e6.txt.gz"))
    tree = ast.parse((ASSETS / "clip/clip.py").read_text(encoding="utf-8"))
    function = next(node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == "tokenize")
    namespace = {"Union": Union, "List": List, "torch": torch, "version": version, "_tokenizer": tokenizer}
    exec(compile(ast.Module(body=[function], type_ignores=[]), "pinned-official-tokenize-only", "exec"), namespace)
    return manifest, tokenizer, namespace["tokenize"]


def main():
    manifest, tokenizer, tokenize = official_oracle()
    vocabulary = [tokenizer.decoder[i] for i in range(len(tokenizer.decoder))]
    manifest["vocabulary"] = {"size": len(vocabulary), "bos": 49406, "eos": 49407, "padding_value": 0,
        "ordered_vocabulary_sha256": digest_json(vocabulary),
        "ordered_byte_map_sha256": digest_json(list(map(list, tokenizer.byte_encoder.items()))),
        "hash_serialization": "UTF-8 JSON ensure_ascii=False separators=(',',':'), no trailing newline"}
    (ASSETS / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    manifest_sha = hashlib.sha256((ASSETS / "manifest.json").read_bytes()).hexdigest()
    records = [("real", None, None, None)] + [
        ("fake", "EFS", "diffusion", "DDPM"),
        ("fake", "EFS", "diffusion", "LatentDiffusion"),
        ("fake", "EFS", "diffusion", "CollaborativeDiffusion"),
        ("fake", "EFS", "GAN", "StyleGAN3"),
        ("fake", "FS", "diffusion", "DiffFace"),
        ("fake", "FS", "GAN", "FSLSD"),
        ("fake", "FS", "GAN", "FaceSwapper"),
        ("fake", "AM", "diffusion", "Diffae"),
        ("fake", "AM", "GAN", "LatentTransformer"),
    ]
    type_text = {"EFS": "A photo of an entire synthesized face", "FS": "A photo of an identity swapped face",
                 "AM": "A photo of an attribute manipulated face"}
    cases = []
    for index, (authenticity, manipulation, family, generator) in enumerate(records):
        prompts = ["A photo of a real face"] * 4 if authenticity == "real" else [
            "A photo of a fake face", type_text[manipulation],
            f"A photo generated by the {family}-based model",
            f"The source generative model of this photo is {generator}"]
        segments = tokenize(prompts, context_length=77, truncate=False).to(torch.int64)
        cases.append({"metadata": {"sample_id": f"golden-{index}", "authenticity": authenticity,
                      "manipulation": manipulation, "family": family, "generator": generator},
                      "prompts": prompts, "segments": segments.tolist(), "ids": segments.reshape(308).tolist(),
                      "payload_lengths": [len(tokenizer.encode(p)) for p in prompts]})
    texts = list(dict.fromkeys([p for case in cases for p in case["prompts"]])) + [
        "", "  A PHOTO\t of a\nreal face  ", "caf\u00e9 na\u00efve \u6771\u4eac \U0001f642", "Fran\u00c3\u00a7ais",
        "A &amp;amp; B &lt;face&gt;", "We're testing: 123, can't!", "<|startoftext|>", "<|endoftext|>",
        "face " * 75, "face " * 76,
    ]
    text_cases = []
    for text in texts:
        item = {"text": text, "payload_ids": tokenizer.encode(text)}
        try:
            item["segment"] = tokenize([text], context_length=77, truncate=False)[0].tolist()
            item["overflow"] = False
        except RuntimeError:
            item["overflow"] = True
        text_cases.append(item)
    result = {"oracle": "Unmodified official SimpleTokenizer and AST-extracted official tokenize; no mfvlr imports",
              "commit": manifest["commit"], "asset_manifest_sha256": manifest_sha,
              "oracle_environment": {name: importlib.metadata.version(name) for name in
                                     ("torch", "ftfy", "regex", "wcwidth", "packaging")},
              "prompt_cases": cases, "text_cases": text_cases}
    destination = ROOT / "tests/foundation/fixtures/golden_tokens.json"
    destination.parent.mkdir(parents=True, exist_ok=True)
    data = (json.dumps(result, ensure_ascii=True, indent=2) + "\n").encode()
    if destination.exists() and destination.read_bytes() != data:
        raise RuntimeError("Golden oracle changed: refusing to overwrite existing fixtures")
    destination.write_bytes(data)
    print("manifest", manifest_sha)
    print("vocabulary", manifest["vocabulary"])
    print("golden", hashlib.sha256(data).hexdigest(), len(cases), len(text_cases))
    wheel_records = {}
    requirements = []
    for wheel in sorted((ROOT / "artifacts/phase2c1/wheels").glob("*.whl")):
        name, ver = wheel.name.split("-")[:2]
        sha = hashlib.sha256(wheel.read_bytes()).hexdigest()
        wheel_records[wheel.name] = {"sha256": sha, "bytes": wheel.stat().st_size}
        requirements.append(f"{name}=={ver} --hash=sha256:{sha}")
    (ROOT / "artifacts/phase2c1/dependency_wheels.json").write_text(json.dumps(wheel_records, indent=2)+"\n")
    (ROOT / "configs/foundation_requirements.lock").write_text("\n".join(requirements)+"\n")


if __name__ == "__main__":
    main()
